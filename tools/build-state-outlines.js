// Regenerates web/state-outlines.js: simplified outlines of the covered states,
// used as the shape of state and local land icons in popups.
// Source: U.S. Census Bureau TIGERweb state boundaries (public domain).
// Run with: node tools/build-state-outlines.js
const fs = require("node:fs");
const path = require("node:path");

const states = [
  ["06", "CA"], ["41", "OR"], ["53", "WA"], ["16", "ID"], ["32", "NV"],
  ["49", "UT"], ["04", "AZ"], ["08", "CO"], ["35", "NM"], ["48", "TX"],
  ["02", "AK"], ["15", "HI"],
];
// Half the Web Mercator world width, used to move Aleutian islands west of 180° next to Alaska.
const mercatorHalfWorld = 20037508.34;
// Hawaii's icon shows only the main islands, not the Northwestern Hawaiian Islands chain.
const westLimit = { HI: (-161 * mercatorHalfWorld) / 180 };
// Island chains have no interior large enough for the symbol, so it sits in open sea beside them.
const symbolPlacement = { HI: { center: [24, 76], symbolSize: 46 } };
const service = "https://tigerweb.geo.census.gov/arcgis/rest/services/TIGERweb/State_County/MapServer/0/query";
const size = 100;
// Rings smaller than this share of the state's largest ring (small islands) are left out.
const minRingShare = 0.01;

function ringArea(ring) {
  let area = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    area += (ring[j][0] + ring[i][0]) * (ring[j][1] - ring[i][1]);
  }
  return Math.abs(area / 2);
}

function insideRings(x, y, rings) {
  let inside = false;
  rings.forEach((ring) => {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
    }
  });
  return inside;
}

function distanceToEdges(x, y, rings) {
  let best = Infinity;
  rings.forEach((ring) => {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [ax, ay] = ring[j];
      const [bx, by] = ring[i];
      const lengthSquared = (bx - ax) ** 2 + (by - ay) ** 2 || 1;
      const t = Math.max(0, Math.min(1, ((x - ax) * (bx - ax) + (y - ay) * (by - ay)) / lengthSquared));
      best = Math.min(best, Math.hypot(x - (ax + t * (bx - ax)), y - (ay + t * (by - ay))));
    }
  });
  return best;
}

// The point inside the outline farthest from its edges, where the category symbol goes.
function symbolCenter(rings) {
  let best = [size / 2, size / 2, -1];
  for (let x = 0; x <= size; x += 1) {
    for (let y = 0; y <= size; y += 1) {
      if (!insideRings(x, y, rings)) continue;
      const distance = distanceToEdges(x, y, rings);
      if (distance > best[2]) best = [x, y, distance];
    }
  }
  return [best[0], best[1]];
}

async function main() {
  const params = new URLSearchParams({
    where: `STATE IN (${states.map(([fips]) => `'${fips}'`).join(",")})`,
    outFields: "STATE",
    outSR: "3857",
    maxAllowableOffset: "6000",
    geometryPrecision: "0",
    f: "json",
  });
  const response = await fetch(`${service}?${params}`);
  const data = await response.json();
  if (!data.features?.length) throw new Error("No state boundaries returned.");
  const codeByFips = new Map(states);
  const outlines = {};
  data.features.forEach((feature) => {
    const code = codeByFips.get(String(feature.attributes.STATE).padStart(2, "0"));
    const rings = feature.geometry.rings.map((ring) =>
      ring.map(([x, y]) => [x > 0 ? x - 2 * mercatorHalfWorld : x, y]),
    );
    const inRange = rings.filter((ring) => !(code in westLimit) || ring.every(([x]) => x >= westLimit[code]));
    const largest = Math.max(...inRange.map(ringArea));
    const kept = inRange.filter((ring) => ringArea(ring) >= largest * minRingShare);
    const xs = kept.flat().map((point) => point[0]);
    const ys = kept.flat().map((point) => point[1]);
    const [minX, maxX, minY, maxY] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
    const scale = size / Math.max(maxX - minX, maxY - minY);
    const offsetX = (size - (maxX - minX) * scale) / 2;
    const offsetY = (size - (maxY - minY) * scale) / 2;
    const scaled = kept.map((ring) => {
      const points = ring.map(([x, y]) => [
        Math.round(offsetX + (x - minX) * scale),
        Math.round(offsetY + (maxY - y) * scale),
      ]);
      return points.filter((point, index) => index === 0 || point.join() !== points[index - 1].join());
    });
    outlines[code] = {
      path: scaled.map((points) => `M${points.map((point) => point.join(" ")).join("L")}Z`).join(""),
      center: symbolCenter(scaled),
      ...symbolPlacement[code],
    };
  });
  const missing = states.map(([, code]) => code).filter((code) => !outlines[code]);
  if (missing.length) throw new Error(`Missing outlines: ${missing.join(", ")}`);
  const ordered = Object.fromEntries(states.map(([, code]) => [code, outlines[code]]));
  const output = `// Generated by tools/build-state-outlines.js from U.S. Census Bureau TIGERweb
// state boundaries (public domain). Simplified SVG paths in a 0-${size} box, and the
// point inside each outline farthest from its edges.
window.CampgroundlessStateOutlines = ${JSON.stringify(ordered, null, 2)};
`;
  fs.writeFileSync(path.join(__dirname, "..", "web", "state-outlines.js"), output);
  console.log(`Wrote ${output.length} bytes`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
